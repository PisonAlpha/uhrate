-- UHRATE dev/test schema — derived from the existing (production) Supabase
-- project's live structure, for setting up an ISOLATED dev/test project.
--
-- METHOD: The Supabase CLI could not be used (no authenticated CLI session —
-- no SUPABASE_ACCESS_TOKEN and not logged in — and no raw Postgres database
-- password was available; only the project URL, anon key, and service-role
-- key exist in .env.local, which are HTTP/JWT credentials, not a Postgres
-- wire-protocol connection). A direct `information_schema`/`pg_catalog` SQL
-- connection was equally unavailable for the same reason (no DB password).
--
-- Instead, this was derived from a single, read-only HTTPS GET request to
-- the project's own PostgREST OpenAPI description endpoint
-- (`{SUPABASE_URL}/rest/v1/`, Accept: application/openapi+json), authenticated
-- with the service-role key. This endpoint is generated by PostgREST itself
-- from the live `information_schema`, server-side — it is read-only and does
-- not touch or return any row data. Source Postgres version reported: 14.5.
--
-- CONFIRMED (directly observed from the response):
--   - table names, column names
--   - column data types (as Postgres type names/formats)
--   - nullability (NOT NULL vs nullable)
--   - column defaults (including gen_random_uuid(), now(), literal defaults)
--   - primary keys (PostgREST explicitly annotates PK columns)
--   - absence of any foreign-key relationships: PostgREST annotates FK
--     columns in the same way it annotates PKs, and no such annotation
--     appeared on any column in any of the 11 tables below — consistent
--     with the application code, which joins everything by plain `email`
--     strings rather than DB-level foreign keys.
--
-- NOT CAPTURED (this introspection method cannot expose these; they are
-- deliberately OMITTED below rather than invented):
--   - UNIQUE constraints (e.g. users.email, users.wallet_address,
--     verifications.sha256_hash, verifications.certificate_id,
--     *_registry.registry_id, api_keys.api_key, identity_badges.badge_id,
--     payments.tx_hash, presale_purchases.tx_hash — all of these are
--     treated as effectively-unique by application logic via .eq() lookups
--     and pre-insert duplicate checks, but none of that proves a DB-level
--     UNIQUE constraint actually exists; it was not observable here)
--   - CHECK constraints
--   - indexes beyond the implicit primary-key index
--   - triggers
--   - Row Level Security policies (moot for this app today — every route
--     uses the service-role key, which bypasses RLS regardless — but still
--     a schema component this method can't see)
--   - sequences (none expected/observed; all PKs use gen_random_uuid(), not
--     serial/identity columns)
--   - enums/custom types (none observed among these 11 tables — every
--     column uses a standard built-in Postgres type)
--
-- An additional 12th table, `certificates`, was also found in the live
-- project's exposed schema. It is NOT included below and NOT referenced
-- anywhere in the application code reviewed in this engagement — flagging
-- its existence rather than silently omitting or silently including it.
--
-- gen_random_uuid() is a built-in Postgres 13+ function (no CREATE EXTENSION
-- needed on Postgres 14.5, the version this project reported).

CREATE TABLE users (
  id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  email text NOT NULL,
  full_name text,
  role text DEFAULT 'individual',
  verified_badge boolean DEFAULT false,
  credits integer DEFAULT 10,
  created_at timestamptz DEFAULT now(),
  password_hash text,
  email_verified boolean DEFAULT false,
  verification_token text,
  token_expires_at timestamptz,
  plan_expires_at timestamptz,
  wallet_address text
);

CREATE TABLE wallet_nonces (
  id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  wallet_address text NOT NULL,
  nonce text NOT NULL,
  expires_at timestamptz NOT NULL,
  created_at timestamptz DEFAULT now()
);

CREATE TABLE verifications (
  id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  file_name text NOT NULL,
  file_type text NOT NULL,
  file_size integer,
  sha256_hash text NOT NULL,
  originality_score integer,
  ai_score integer,
  deepfake_score integer,
  manipulation_score integer,
  trust_score integer,
  rating text,
  blockchain_tx text,
  blockchain_chain text,
  certificate_id text,
  ipfs_hash text,
  created_at timestamptz DEFAULT now(),
  nft_tx text,
  nft_token_id integer,
  nft_contract text,
  user_email text
);

