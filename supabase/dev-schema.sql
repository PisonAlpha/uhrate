  id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  user_email text NOT NULL,
  key_name text NOT NULL,
  api_key text NOT NULL,
  calls_used integer DEFAULT 0,
  calls_limit integer DEFAULT 1000,
